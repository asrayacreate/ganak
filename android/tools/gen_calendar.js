/* Writes CalendarData.java from the web app's own tables (index.html), so the home-screen widget and
   the app always agree: BS month lengths, festival / holiday list, month, weekday and tithi names.
   Run from the repo root:  node android/tools/gen_calendar.js  (the Android build workflow runs it too). */
var fs = require("fs"), path = require("path"), vm = require("vm");
var root = path.join(__dirname, "..", ".."), html = fs.readFileSync(path.join(root, "index.html"), "utf8");
function grab(name){   /* the literal assigned to "var NAME = ...;" (ends at the first "];" or "};" closing it) */
  var m = html.match(new RegExp("var " + name + "\\s*=\\s*([\\[{][\\s\\S]*?[\\]}]);"));
  if(!m) throw new Error("not found in index.html: " + name);
  return vm.runInNewContext("(" + m[1] + ")");
}
function num(name){ var m = html.match(new RegExp("var " + name + "\\s*=\\s*(\\d+);")); if(!m) throw new Error(name); return +m[1]; }
var D = { BS_START_YEAR:num("BS_START_YEAR"), BS_DATA:grab("BS_DATA"), BS_MONTHS:grab("BS_MONTHS"), BS_MONTHS_EN:grab("BS_MONTHS_EN"),
          WEEKDAYS:grab("WEEKDAYS"), WEEKDAYS_EN:grab("WEEKDAYS_EN"), TITHI:grab("TITHI"), TITHI_EN:grab("TITHI_EN"), HOLI:grab("HOLI") };
var ep = html.match(/var BS_EPOCH_UTC = Date\.UTC\((\d+),(\d+),(\d+)\)/);
if(!ep) throw new Error("BS_EPOCH_UTC");
var epochDay = Date.UTC(+ep[1], +ep[2], +ep[3]) / 864e5;
function q(s){ return JSON.stringify(s); }
function arr(a){ return "{" + a.map(q).join(", ") + "}"; }
var rows = D.BS_DATA.map(function(r){ return "    {" + r.join(",") + "}"; }).join(",\n");
var fest = [];
Object.keys(D.HOLI).forEach(function(y){ D.HOLI[y].forEach(function(h){ fest.push("    {" + [y, h[0], h[1]].join(",") + "}"); }); });
var festTxt = [];
Object.keys(D.HOLI).forEach(function(y){ D.HOLI[y].forEach(function(h){ festTxt.push("    {" + [q(h[2]), q(h[3]), q(h[4])].join(", ") + "}"); }); });
var out = "/* GENERATED by android/tools/gen_calendar.js from index.html — do not edit by hand. */\n"
  + "package io.github.asrayacreate.twa;\n\nfinal class CalendarData {\n  private CalendarData(){}\n"
  + "  static final int BS_START_YEAR = " + D.BS_START_YEAR + ";\n"
  + "  /** days since 1970-01-01 of 1 Baishakh " + D.BS_START_YEAR + " */\n  static final long BS_EPOCH_DAY = " + epochDay + "L;\n"
  + "  static final int[][] BS_DATA = {\n" + rows + "\n  };\n"
  + "  static final String[] BS_MONTHS = " + arr(D.BS_MONTHS) + ";\n"
  + "  static final String[] BS_MONTHS_EN = " + arr(D.BS_MONTHS_EN) + ";\n"
  + "  static final String[] WEEKDAYS = " + arr(D.WEEKDAYS) + ";\n"
  + "  static final String[] WEEKDAYS_EN = " + arr(D.WEEKDAYS_EN) + ";\n"
  + "  static final String[] TITHI = " + arr(D.TITHI) + ";\n"
  + "  static final String[] TITHI_EN = " + arr(D.TITHI_EN) + ";\n"
  + "  /** festival / holiday dates: BS year, month, day */\n  static final int[][] FEST_DATE = {\n" + fest.join(",\n") + "\n  };\n"
  + "  /** kind (h = public holiday, v = valley, f = festival), Nepali name, English name */\n  static final String[][] FEST_TEXT = {\n" + festTxt.join(",\n") + "\n  };\n}\n";
var dst = path.join(__dirname, "..", "app", "src", "main", "java", "io", "github", "asrayacreate", "twa", "CalendarData.java");
fs.mkdirSync(path.dirname(dst), {recursive:true});
fs.writeFileSync(dst, out);
console.log("CalendarData.java: " + D.BS_DATA.length + " BS years from " + D.BS_START_YEAR + ", " + fest.length + " festival days");
